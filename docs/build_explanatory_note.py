page(9, "3.1. Выбор числа групп по Gap", "gap")
p("Автоматический режим сравнивает компактность групп с тем, что получилось бы у данных без специально заложенных сгущений. Контрольная модель - равномерное распределение σ между минимумом и максимумом исходного набора.")
h("Критерий")
p("Для каждого K строится разбиение полной связью и вычисляется внутригрупповой разброс W(K): сумма квадратов отклонений σ от среднего своей группы. Чтобы единицы измерения не влияли на вычисления, σ предварительно переводятся в диапазон [0; 1].")
f("W(K) = Σ<sub>g=1..K</sub> Σ<sub>i∈Gg</sub> (σ<sub>i</sub> - σ̄<sub>g</sub>)<super>2</super>.<br/>Gap(K) = mean[ln W<sub>ref</sub>(K)] - ln W(K).")
p("Генерируются B = 100 контрольных наборов такого же размера. Каждый также делится полной связью. Чем больше Gap, тем сильнее компактность реальных групп превосходит контрольную модель [5, 6]. Общий множитель C² из расстояния по срезам сокращается в разности логарифмов.")
h("Правило, реализованное в программе")
p("Просматриваются K от 1 до min(10, N - 1, числа различных σ). Находится K* с наибольшим Gap. Затем берётся наименьшее K, значение которого не хуже максимума более чем на одну оценку погрешности:")
f("s(K) = SD[ln W<sub>ref</sub>(K)] · √(1 + 1/B).<br/>K<sub>выбр</sub> = min {K : Gap(K) ≥ Gap(K*) - s(K*)}.")
p("Это вариант global 1-SE, соответствующий правилу globalSEmax, а не правило сравнения только соседних K. Он позволяет предпочесть более простое разбиение, когда прибавка качества укладывается в разброс контрольного эксперимента. Seed контрольных наборов фиксирован: 42.")
h("Почему может получиться одна или три группы")
